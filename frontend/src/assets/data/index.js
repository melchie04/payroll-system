// Timesheet intake. One sheet covers one employee and one half-month, so a pay
// period that straddles the 15th is fed by more than one sheet.
// clean produces a sheet the OCR read without hesitation, used for the sheets that
// come through with nothing flagged at all.
function sheetRows(half, month, year, pattern, clean = false, start = "07:30") {
  const first = half === "1-15" ? 1 : 16;
  const count = half === "1-15" ? 15 : 16;
  const [sh, sm] = start.split(":").map(Number);
  const at = (mins) => {
    const total = sh * 60 + sm + mins;
    return `${String(Math.floor(total / 60)).padStart(2, "0")}:${String(total % 60).padStart(2, "0")}`;
  };
  return Array.from({ length: count }, (_, i) => {
    const day = first + i;
    const shift = pattern[i % pattern.length];
    const lateDay = Boolean(shift) && day % 5 === 0;
    const overtime = Boolean(shift) && i % 7 === 4;
    return {
      day,
      date: `${month} ${day}, ${year}`,
      amIn: shift ? at(lateDay ? 15 : 0) : "",
      amOut: shift ? at(270) : "",
      pmIn: shift ? at(330) : "",
      pmOut: shift ? at(570) : "",
      otIn: overtime ? at(570) : "",
      otOut: overtime ? at(690) : "",
      late: lateDay ? 15 : 0,
      lowConfidence: clean ? [] : shift && (day % 4 === 0 ? ["amIn"] : day % 6 === 0 ? ["pmOut"] : []),
    };
  });
}

